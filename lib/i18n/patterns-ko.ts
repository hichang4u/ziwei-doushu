/** 单条文本：精确表 → 动态规则 → 原样 */
export function translatePatternText(zh: string): string {
  const exact = TEXT_KO[zh];
  if (exact) return exact;
  for (const [re, fn] of DYNAMIC_RULES) {
    const m = re.exec(zh);
    if (m) return fn(...m.slice(1));
  }
  return zh;
}

/** 出处《书名·篇名》 → 『한국어』 */
export function translateSource(zh: string): string {
  const m = /^《([^·》]+)(?:·([^》]+))?》$/.exec(zh);
  if (!m || !BOOK_KO[m[1]] || (m[2] && !CHAPTER_KO[m[2]])) return zh;
  return `『${BOOK_KO[m[1]]}${m[2] ? `·${CHAPTER_KO[m[2]]}` : ''}』`;
}

/** 格局名 → KoTerm（含动态「星名 + 化禄入命」）；查不到返回 null */
export function patternNameKo(zh: string): { star?: string; term: KoTerm } | null {
  if (PATTERN_NAMES_KO[zh]) return { term: PATTERN_NAMES_KO[zh] };
  for (const [suffix, term] of Object.entries(NAME_SUFFIX_KO)) {
    if (zh.endsWith(suffix) && zh.length > suffix.length) return { star: zh.slice(0, -suffix.length), term };
  }
  return null;
}

/** 整条 Pattern 译成韩文（名称留给显示层按术语模式格式化，这里只译正文） */
