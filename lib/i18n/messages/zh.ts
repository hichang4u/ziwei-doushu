/** 把 zh 的字面量类型放宽成「同结构的 string / 同参数函数」，供 ko.ts 约束 */
type Widen<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends readonly string[]
    ? string[]
    : T extends string
      ? string
      : { [K in keyof T]: Widen<T[K]> };

