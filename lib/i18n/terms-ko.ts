/**
 * 纯韩文模式下读音相同、需要附汉字才能区分的术语：
 * 천월（天鉞 / 天月）、천상（天相 / 天傷）等。由表自动算出，避免手维护漏项。
 */
export const HANGUL_COLLISIONS: ReadonlySet<string> = (() => {
  const byKo = new Map<string, string[]>();
  for (const [zh, t] of Object.entries({ ...MAJOR_STARS_KO, ...OTHER_STARS_KO, ...PALACES_KO })) {
    byKo.set(t.ko, [...(byKo.get(t.ko) ?? []), zh]);
  }
  return new Set([...byKo.values()].filter((zhs) => zhs.length > 1).flat());
})();
